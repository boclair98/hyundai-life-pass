CREATE TABLE vehicles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id VARCHAR(80) NOT NULL UNIQUE,
  name VARCHAR(80) NOT NULL,
  trim VARCHAR(120) NOT NULL,
  plate VARCHAR(30) NOT NULL,
  powertrain VARCHAR(20) NOT NULL,
  battery_soc INTEGER NOT NULL,
  battery_soh INTEGER NOT NULL,
  health_score INTEGER NOT NULL,
  range_km INTEGER NOT NULL,
  odometer_km INTEGER NOT NULL,
  next_service_km INTEGER NOT NULL,
  location VARCHAR(100) NOT NULL,
  software_version VARCHAR(20) NOT NULL,
  charging_state VARCHAR(40) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE vehicle_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
  type VARCHAR(30) NOT NULL,
  title VARCHAR(140) NOT NULL,
  detail VARCHAR(240) NOT NULL,
  tone VARCHAR(16) NOT NULL,
  signature VARCHAR(80) NOT NULL,
  occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE releases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version VARCHAR(20) NOT NULL,
  title VARCHAR(180) NOT NULL,
  status VARCHAR(20) NOT NULL,
  target VARCHAR(120) NOT NULL,
  progress INTEGER NOT NULL,
  risk VARCHAR(20) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_vehicle_events_vehicle_time ON vehicle_events(vehicle_id, occurred_at);
