ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS source VARCHAR(40) NOT NULL DEFAULT 'SAMPLE';

CREATE TABLE hyundai_oauth_states (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  state_token VARCHAR(100) NOT NULL UNIQUE,
  actor_id VARCHAR(160) NOT NULL,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  consumed BOOLEAN NOT NULL
);

CREATE TABLE hyundai_connections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id VARCHAR(160) NOT NULL UNIQUE,
  access_token_encrypted VARCHAR(2048) NOT NULL,
  refresh_token_encrypted VARCHAR(2048) NOT NULL,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  status VARCHAR(32) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_hyundai_oauth_actor ON hyundai_oauth_states(actor_id, expires_at);
